--comment: create a branch_addresses table for routing and assignment strategy queries
CREATE TABLE organizations.branch_addresses (
    id              UUID         NOT NULL DEFAULT gen_random_uuid(),
    address_tag     VARCHAR(50)  NOT NULL,
    branch_id       UUID         NOT NULL,
    city            VARCHAR(100) NOT NULL,
    country         VARCHAR(100) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    created_by      VARCHAR(36)  NOT NULL,
    latitude        DECIMAL(10, 8),
    longitude       DECIMAL(11, 8),
    postal_code     VARCHAR(20),
    street_address  VARCHAR(500) NOT NULL,
    updated_at      TIMESTAMPTZ,
    updated_by      VARCHAR(36),

    CONSTRAINT pk_branch_addresses
        PRIMARY KEY (id),

    CONSTRAINT fk_branch_addresses_branch
        FOREIGN KEY (branch_id)
            REFERENCES organizations.branches (id)
            ON DELETE CASCADE
);

