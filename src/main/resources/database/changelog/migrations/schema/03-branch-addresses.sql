--comment: create indexes for the branch_addresses table
CREATE INDEX idx_branch_addresses_branch          ON organizations.branch_addresses (branch_id);
CREATE INDEX idx_branch_addresses_geocode         ON organizations.branch_addresses (latitude, longitude);
CREATE UNIQUE INDEX uq_branch_addresses_branch_tag ON organizations.branch_addresses (branch_id, address_tag);

