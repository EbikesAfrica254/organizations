    'Compliance documents with lifecycle tracking. Documents begin as PENDING on upload initiation, '
        'transition to UPLOADED on client confirmation, ACTIVE on checker approval, REPLACED when a '
        'newer version supersedes them, and EXPIRED when their expiry date is reached. '
        'file_storage_url is required for all non-PENDING documents enforced via check constraint.';

