        CHECK (status = 'PENDING' OR file_storage_url IS NOT NULL);

ALTER TABLE organizations.documents
    ADD CONSTRAINT chk_documents_status
        CHECK (status IN ('ACTIVE', 'EXPIRED', 'PENDING', 'REPLACED', 'UPLOADED'));

ALTER TABLE organizations.documents
    ADD CONSTRAINT chk_documents_type
        CHECK (document_type IN (
                                 'BUSINESS_REGISTRATION_CERT',
                                 'CERTIFICATE_OF_COMPLIANCE',
                                 'CERTIFICATE_OF_INCORPORATION',
                                 'COUNTY_PERMIT',
                                 'HEALTH_CERTIFICATE',
                                 'KRA_PIN_CERT',
                                 'MEMORANDUM_ARTICLES',
                                 'NATIONAL_ID',
                                 'PARTNERSHIP_DEED'));

