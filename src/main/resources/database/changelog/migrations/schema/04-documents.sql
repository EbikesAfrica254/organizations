CREATE UNIQUE INDEX uq_documents_file_storage_url       ON organizations.documents (file_storage_url) WHERE file_storage_url IS NOT NULL;
CREATE UNIQUE INDEX uq_documents_org_type_active ON organizations.documents (organization_id, document_type) WHERE status = 'ACTIVE';

