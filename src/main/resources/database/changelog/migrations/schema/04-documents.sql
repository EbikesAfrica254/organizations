--comment: create a documents table to manage compliance documentation
CREATE TABLE organizations.documents (
     id                      UUID         NOT NULL DEFAULT gen_random_uuid(),
     created_at              TIMESTAMPTZ  NOT NULL,
     created_by              VARCHAR(36)  NOT NULL,
     document_type           VARCHAR(50)  NOT NULL,
     expiry_date             DATE,
     file_name               VARCHAR(255),
     file_size_bytes         BIGINT,
     file_storage_url        VARCHAR(1000),
     mime_type               VARCHAR(100),
     organization_id         UUID,
     replaces_document_id    UUID,
     status                  VARCHAR(50)  NOT NULL DEFAULT 'PENDING',
     updated_at              TIMESTAMPTZ,
     updated_by              VARCHAR(36),
     uploaded_at             TIMESTAMPTZ,
     version                 BIGINT       NOT NULL DEFAULT 0,

     CONSTRAINT pk_documents
         PRIMARY KEY (id),

     CONSTRAINT fk_documents_organization
         FOREIGN KEY (organization_id)
             REFERENCES organizations.organizations (id)
             ON DELETE RESTRICT,

     CONSTRAINT fk_documents_replaces
         FOREIGN KEY (replaces_document_id)
             REFERENCES organizations.documents (id)
             ON DELETE SET NULL
);

